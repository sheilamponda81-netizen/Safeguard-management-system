-- ============================================================
-- MIGRATION: HikCentral Attendance MVP -- Phase 1 ingestion foundation
-- Date: 2026-09-29
-- ============================================================
--
-- WHAT THIS MIGRATION DOES
-- -----------------------------------------------------------
-- Adds the permanent raw-event ingestion pipeline for HikCentral
-- fingerprint-attendance data: an import-batch audit table, an
-- append-only raw-event table (successful fingerprint punches only), and
-- a person-identity mapping table with full history. Also seeds two new
-- narrowly-scoped permissions and a server-authoritative bulk-ingestion
-- RPC.
--
-- WHAT THIS MIGRATION DELIBERATELY DOES NOT DO
-- -----------------------------------------------------------
-- - Does NOT touch the `attendance` table in any way -- no new column,
--   no new policy, no new trigger. This PR writes zero official
--   attendance rows; that is a later phase (see the approved product
--   decisions, point 9 -- attendance.source will be added immediately
--   before that phase, not here).
-- - Does NOT create an "apply attendance" permission -- only
--   attendance.import_hikcentral and attendance.map_hikcentral_persons,
--   per approved decision point 10 ("implement only the permissions
--   necessary for import/preview/mapping/raw-event management").
-- - Does NOT store a `processing_status` (e.g. 'ignored_unmapped') on
--   hikcentral_raw_events. Per approved decision 5, "unmapped" is a
--   DYNAMIC fact (a person can be mapped later) and must never be frozen
--   onto an immutable raw-event row -- it is always computed at query
--   time as `hikcentral_person_no IS NOT NULL AND EXISTS (an active
--   mapping for it)`.
-- - Does NOT store `mapped_employee_id` on hikcentral_raw_events. Per
--   approved decision 4, resolving an event to an employee is always a
--   JOIN against the CURRENT active mapping, so correcting a mapping
--   automatically and retroactively affects reprocessing of every event
--   already stored -- there is nothing to "fix up" on old rows.
-- - Does NOT persist individual Failed-authentication rows. Per approved
--   decision 6, Failed events are counted/classified into
--   hikcentral_import_batches' summary columns only; the primary raw
--   record is a successful Authorization + "Access Granted by
--   Fingerprint" event. A successful event with NO Person No. IS stored
--   (hikcentral_person_no nullable) -- it is a real fact ("someone
--   authenticated, unknown who"), just never automatically attendance-
--   eligible.
--
-- IDENTITY MODEL
-- -----------------------------------------------------------
-- HikCentral's numeric `Person No.` (e.g. "00000174") is a completely
-- separate identity system from Safeguard's `employee_number`
-- (e.g. "SFG-S-076", generated by generate_employee_number() --
-- 20260804000001_employee_number_generation.sql). There is no
-- mathematical conversion between them (approved decision 2). No column
-- on `employees` is repurposed; hikcentral_person_mappings is the single
-- source of truth for this linkage, and it is explicitly historical:
-- superseding a mapping (e.g. an employee re-enrolled with a new
-- fingerprint-terminal identity) never deletes the old row, it just
-- deactivates it (approved decision 3).
--
-- SEARCH_PATH CONVENTION FOLLOWED
-- -----------------------------------------------------------
-- The new RPC below uses `SET search_path = public, pg_temp` and calls
-- is_current_user_active()/is_business_admin()/has_permission()/
-- region_allowed() normally -- this is safe because, per
-- 20260817000000_functional_role_permissions_foundation.sql, every one
-- of those helpers declares that exact same `SET search_path = public,
-- pg_temp` on itself, so it resolves `profiles`/`role_permissions`
-- correctly regardless of the caller's own search_path. The ONE helper
-- that has never had a SET clause of its own is get_current_tenant_id()
-- (root-caused in 20260831010000_payroll_approval_rpc_search_path_fix.sql)
-- -- this RPC does not call it; tenant_id is read directly off
-- `profiles` in the same single query as every other caller attribute,
-- matching process_payroll_batch's own established pattern
-- (20260817000003_functional_roles_rpc_authorization.sql).
-- ============================================================

-- ============================================================
-- PART 1: hikcentral_import_batches
-- ============================================================
-- One row per upload (Stage 1: Excel; Stage 2: a future API/webhook
-- sync run). Audits WHO imported WHAT, WHEN, and a summary of what the
-- source file/feed actually contained -- including the counts for
-- events that are NEVER individually persisted (Failed rows), so a
-- Failed-heavy upload is still fully auditable without storing every
-- failed row forever. The Excel binary itself is never stored here (no
-- compelling reason found -- the raw events + this summary are the
-- durable record; the source file can be re-uploaded if ever needed,
-- and re-upload is safe by construction, see PART 2's dedup).
CREATE TABLE IF NOT EXISTS hikcentral_import_batches (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id UUID NOT NULL REFERENCES tenants(id) ON DELETE CASCADE DEFAULT get_current_tenant_id(),
  source TEXT NOT NULL DEFAULT 'excel' CHECK (source IN ('excel', 'api')),
  filename TEXT,
  -- SHA-256 of the uploaded file's bytes, computed client-side before
  -- parsing. Two roles: (1) a diagnostic convenience ("this exact file
  -- looks like it was already uploaded as batch X"), and (2) LOAD-BEARING
  -- for anonymous (no Person No.) raw events' fingerprint -- see PART 5's
  -- import_hikcentral_raw_events(), which reads this column back
  -- server-side (never re-trusting a client-supplied value at import
  -- time) to scope an anonymous event's identity to this specific file,
  -- since the visible event fields alone cannot safely distinguish two
  -- different anonymous people (see PART 5's header comment). For an
  -- IDENTIFIED event (has a Person No.), this column plays no role --
  -- event_fingerprint's UNIQUE constraint in PART 2 dedupes those
  -- correctly across OVERLAPPING (not byte-identical) exports on its
  -- own. Nullable/unconstrained deliberately: re-uploading identical
  -- bytes must never be blocked at the file level, only silently no-op
  -- at the per-event level.
  file_fingerprint TEXT,
  imported_by UUID REFERENCES profiles(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'processing' CHECK (status IN ('processing', 'completed', 'failed')),
  total_rows INTEGER,
  authorization_count INTEGER,
  failed_count INTEGER,
  with_person_no_count INTEGER,
  without_person_no_count INTEGER,
  unique_person_no_count INTEGER,
  raw_events_inserted INTEGER,
  exact_duplicates_ignored INTEGER,
  error_message TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_hikcentral_import_batches_tenant_created
  ON hikcentral_import_batches(tenant_id, created_at DESC);

-- ============================================================
-- PART 2: hikcentral_raw_events
-- ============================================================
-- Immutable facts: successful fingerprint-authentication events only
-- (Authentication Result = 'Authorization' AND Event Type = 'Access
-- Granted by Fingerprint' -- enforced server-side in the ingestion RPC,
-- PART 5, not just trusted from the client). One row per real punch,
-- append-only -- nothing here is ever updated by mapping/attendance
-- work; only new rows are ever inserted.
CREATE TABLE IF NOT EXISTS hikcentral_raw_events (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id UUID NOT NULL REFERENCES tenants(id) ON DELETE CASCADE DEFAULT get_current_tenant_id(),
  import_batch_id UUID NOT NULL REFERENCES hikcentral_import_batches(id) ON DELETE CASCADE,
  -- Stage 1 (Excel) vs Stage 2 (future live API/webhook adapter) --
  -- everything downstream (dedup, mapping, attendance calculation) reads
  -- this table without caring which adapter wrote a given row.
  source TEXT NOT NULL DEFAULT 'excel' CHECK (source IN ('excel', 'api')),
  -- Nullable: a successful fingerprint scan can arrive with no Person No.
  -- (238 of 970 Authorization rows in the real sample) -- these are
  -- preserved as real facts but can never be attendance-eligible (no
  -- identity to map). TEXT, never numeric -- "00000174"'s leading zeros
  -- are meaningful and must never be reinterpreted.
  hikcentral_person_no TEXT,
  first_name TEXT,
  last_name TEXT,
  event_time TIMESTAMPTZ NOT NULL,
  access_point TEXT,
  card_reader TEXT,
  -- Always 'Authorization' by construction today (only successful events
  -- are ever inserted) -- kept as its own column, not dropped, because
  -- the future API adapter (Stage 2) writes into this SAME table and may
  -- observe a slightly different successful-result vocabulary; a CHECK
  -- pinned to today's one observed string would need a migration the
  -- moment Stage 2 lands.
  authentication_result TEXT NOT NULL,
  event_type TEXT NOT NULL,
  -- Always 'Undefined' in every real row observed so far -- HikCentral
  -- never populates this. Kept for forward-compatibility only.
  attendance_type TEXT,
  -- Deterministic dedup key -- see the ingestion RPC (PART 5) for the
  -- canonical algorithm and its documented limits.
  event_fingerprint TEXT NOT NULL,
  -- ONLY the known textual/event-metadata columns this table already
  -- models as first-class fields (Person No., First/Last Name, Time,
  -- Access Point, Card Reader, Authentication Result, Event Type,
  -- Attendance Type -- see hikcentralExcelParser.ts's
  -- REQUIRED_HEADERS/OPTIONAL_KNOWN_HEADERS, which is exactly what
  -- rawPayload is built from). Deliberately NEVER includes the export's
  -- two "Captured Picture" columns, "Profile", or any other
  -- image/binary-bearing column -- this table must not quietly become
  -- an image-storage table. (An earlier draft of this comment
  -- inaccurately claimed this held the complete original spreadsheet
  -- row; corrected here to match what the parser actually captures.)
  raw_payload JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  -- Exact-duplicate-import protection (approved decision / PR scope item
  -- D: "a re-upload of the exact same export must not create duplicate
  -- raw events... overlapping exports should also deduplicate identical
  -- events"). Two genuinely distinct real punches 3+ seconds apart get
  -- different event_time -> different fingerprint -> both rows are kept
  -- (see PART 5's header comment for the one acknowledged case this
  -- cannot distinguish: two truly identical-second duplicate events).
  UNIQUE (tenant_id, event_fingerprint)
);

CREATE INDEX IF NOT EXISTS idx_hikcentral_raw_events_tenant_time
  ON hikcentral_raw_events(tenant_id, event_time);
CREATE INDEX IF NOT EXISTS idx_hikcentral_raw_events_tenant_person
  ON hikcentral_raw_events(tenant_id, hikcentral_person_no);
CREATE INDEX IF NOT EXISTS idx_hikcentral_raw_events_batch
  ON hikcentral_raw_events(import_batch_id);

-- ============================================================
-- PART 3: hikcentral_person_mappings
-- ============================================================
-- HikCentral Person No. <-> Safeguard employee_id, WITH HISTORY.
-- Deliberately no `mapped_employee_id` column on hikcentral_raw_events
-- (PART 2) -- every consumer resolves identity by joining a raw event's
-- hikcentral_person_no against the CURRENTLY ACTIVE row here, so
-- correcting a wrong mapping automatically and retroactively fixes every
-- already-stored event's resolvable identity with no backfill needed.
CREATE TABLE IF NOT EXISTS hikcentral_person_mappings (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id UUID NOT NULL REFERENCES tenants(id) ON DELETE CASCADE DEFAULT get_current_tenant_id(),
  hikcentral_person_no TEXT NOT NULL,
  employee_id UUID NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  -- How this mapping was arrived at -- an audit trail of whether a human
  -- typed it in cold or approved a computer-suggested guess. Names are
  -- NEVER the permanent link (that's employee_id above); this column
  -- only records how the SUGGESTION, if any, was generated.
  match_method TEXT NOT NULL CHECK (match_method IN ('manual', 'suggested_name', 'suggested_employee_number')),
  confirmed_by UUID REFERENCES profiles(id) ON DELETE SET NULL,
  confirmed_at TIMESTAMPTZ,
  is_active BOOLEAN NOT NULL DEFAULT true,
  superseded_at TIMESTAMPTZ,
  superseded_by UUID REFERENCES profiles(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- "one active mapping for a given HikCentral Person No. per tenant"
-- (approved decision 3, hard requirement). A partial index, not a table
-- CHECK/UNIQUE constraint, because historical (is_active = false) rows
-- for the SAME person_no must remain completely unconstrained relative
-- to each other -- that is exactly what preserves history instead of
-- requiring a delete before re-mapping.
CREATE UNIQUE INDEX IF NOT EXISTS uq_hikcentral_person_mappings_active_person
  ON hikcentral_person_mappings (tenant_id, hikcentral_person_no)
  WHERE is_active;

-- "at most one active Person No. per employee" (approved decision 3,
-- "if practical" requirement) -- same partial-unique technique. If an
-- employee is later re-enrolled on the fingerprint terminal with a new
-- Person No., the old mapping must be superseded (is_active = false)
-- before a new active one for that employee can be inserted; the OLD row
-- is kept forever, not deleted.
CREATE UNIQUE INDEX IF NOT EXISTS uq_hikcentral_person_mappings_active_employee
  ON hikcentral_person_mappings (tenant_id, employee_id)
  WHERE is_active;

CREATE INDEX IF NOT EXISTS idx_hikcentral_person_mappings_tenant
  ON hikcentral_person_mappings(tenant_id);

-- ============================================================
-- PART 4: RLS
-- ============================================================
ALTER TABLE hikcentral_import_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE hikcentral_raw_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE hikcentral_person_mappings ENABLE ROW LEVEL SECURITY;

-- FORCE ROW LEVEL SECURITY is DELIBERATELY NOT applied to any of these
-- three tables -- do not add it. By default, RLS policies do not apply
-- to a table's OWNER, and a SECURITY DEFINER function executes with the
-- privileges of ITS OWNER; import_hikcentral_raw_events() (PART 5) is
-- how every row in hikcentral_raw_events is written, and that table
-- has NO client-facing INSERT policy at all -- the RPC's insert only
-- succeeds because it runs as the (table-owning) function owner, which
-- RLS does not restrict unless FORCE is set. Adding FORCE ROW LEVEL
-- SECURITY here would apply RLS to the owner too, and since there is no
-- INSERT policy for ANY role on this table, that would break the
-- ingestion pipeline entirely (every insert, including the RPC's own,
-- would be rejected). The same reasoning applies to
-- hikcentral_import_batches' status/count columns, which only the RPC
-- ever updates via a table with no client-facing UPDATE policy. This is
-- the same owner-bypass mechanism every other SECURITY DEFINER
-- RPC in this schema (e.g. approve_payroll_run, process_payroll_batch)
-- already relies on -- none of them, and no table they write through,
-- uses FORCE ROW LEVEL SECURITY either.

-- hikcentral_import_batches / hikcentral_raw_events have no employee_id
-- of their own (raw events are tenant-wide facts, not yet linked to any
-- employee -- linkage only exists once a mapping is confirmed), so
-- region-scoping via employee_region_allowed() does not apply to them,
-- unlike attendance/payroll/employee_deductions. Tenant isolation +
-- active-user + permission gate only, matching the shape every other
-- tenant-scoped (non-employee-linked) table in this schema uses.
--
-- Legacy-role fallback threshold: `<= 2` (Admin/Manager), mirroring
-- `employees`' own threshold (20260908000000) -- HikCentral import/
-- mapping is closely tied to employee-identity management, the same
-- class of action as editing an employee record.

DROP POLICY IF EXISTS "HikCentral import batches: view within tenant, permitted" ON hikcentral_import_batches;
CREATE POLICY "HikCentral import batches: view within tenant, permitted" ON hikcentral_import_batches
FOR SELECT USING (
  is_current_user_active()
  AND (
    is_super_admin()
    OR (
      tenant_id = get_current_tenant_id()
      AND (current_user_role_level() <= 2 OR has_permission('attendance.import_hikcentral'))
    )
  )
);

DROP POLICY IF EXISTS "HikCentral import batches: create within tenant, permitted" ON hikcentral_import_batches;
CREATE POLICY "HikCentral import batches: create within tenant, permitted" ON hikcentral_import_batches
FOR INSERT WITH CHECK (
  is_current_user_active()
  AND (
    is_super_admin()
    OR (
      tenant_id = get_current_tenant_id()
      AND (current_user_role_level() <= 2 OR has_permission('attendance.import_hikcentral'))
    )
  )
);

-- No UPDATE policy for regular callers -- only the ingestion RPC (PART 5,
-- SECURITY DEFINER) ever transitions a batch from 'processing' to
-- 'completed'/'failed' with real counts, so a client can never forge a
-- batch's summary numbers directly. No DELETE policy at all, matching
-- attendance's own "no legitimate caller found" precedent -- an import
-- batch is a permanent audit record.

DROP POLICY IF EXISTS "HikCentral raw events: view within tenant, permitted" ON hikcentral_raw_events;
CREATE POLICY "HikCentral raw events: view within tenant, permitted" ON hikcentral_raw_events
FOR SELECT USING (
  is_current_user_active()
  AND (
    is_super_admin()
    OR (
      tenant_id = get_current_tenant_id()
      AND (current_user_role_level() <= 2 OR has_permission('attendance.import_hikcentral'))
    )
  )
);

-- No client-side INSERT/UPDATE/DELETE policy on hikcentral_raw_events at
-- all -- every row is written exclusively by the ingestion RPC (PART 5,
-- SECURITY DEFINER, re-derives the caller's own tenant server-side). This
-- is the concrete mechanism behind "do not trust tenant_id from the
